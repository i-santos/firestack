import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, resolve } from 'node:path';

function parseEnv(contents) {
  const output = {};
  for (const raw of contents.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const index = line.indexOf('=');
    if (index <= 0) continue;
    const key = line.slice(0, index).trim();
    const value = line.slice(index + 1).trim();
    output[key] = value;
  }
  return output;
}

function getConfig() {
  const path = resolve('firestack/config.json');
  if (!existsSync(path)) {
    throw new Error('missing firestack/config.json. Run: npx firestack install');
  }
  return JSON.parse(readFileSync(path, 'utf8'));
}

function pickClientVars(envVars, prefixes) {
  const entries = Object.entries(envVars).filter(([key]) => prefixes.some((prefix) => key.startsWith(prefix)));
  return Object.fromEntries(entries);
}

function renderEnvironmentFile({ production, envName, values }) {
  return `// Generated by firestack/scripts/angular-env-sync.mjs\nexport const environment = {\n  production: ${production},\n  envName: '${envName}',\n  vars: ${JSON.stringify(values, null, 2)}\n};\n`;
}

function outputPathForEnv(envName) {
  if (envName === 'development') return ['src/environments/environment.ts', 'src/environments/environment.development.ts'];
  if (envName === 'staging') return ['src/environments/environment.staging.ts'];
  if (envName === 'production') return ['src/environments/environment.production.ts'];
  return [`src/environments/environment.${envName}.ts`];
}

function main() {
  const envName = (process.argv[2] ?? 'development').trim();
  const config = getConfig();
  const envFile = config.envFiles?.[envName];
  if (!envFile) {
    console.error(`[firestack] unknown environment: ${envName}`);
    process.exit(1);
  }

  const fullEnvPath = resolve(envFile);
  if (!existsSync(fullEnvPath)) {
    console.error(`[firestack] missing ${envFile}. Copy from firestack/env/examples/${basename(envFile)}.example`);
    process.exit(1);
  }

  const prefixes = config.angular?.exposePrefixes ?? ['NG_APP_', 'VITE_', 'FIREBASE_', 'PUBLIC_'];
  const envVars = parseEnv(readFileSync(fullEnvPath, 'utf8'));
  const clientVars = pickClientVars(envVars, prefixes);

  mkdirSync(resolve('src/environments'), { recursive: true });
  const content = renderEnvironmentFile({
    production: envName === 'production',
    envName,
    values: clientVars,
  });

  const paths = outputPathForEnv(envName);
  for (const path of paths) {
    writeFileSync(resolve(path), content, 'utf8');
    console.log(`[firestack] wrote ${path}`);
  }

  console.log(`[firestack] angular environment synced from ${envFile}`);
}

try {
  main();
} catch (error) {
  const message = error instanceof Error ? error.message : String(error);
  console.error(`[firestack] ${message}`);
  process.exit(1);
}
